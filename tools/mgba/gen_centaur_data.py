#!/usr/bin/env python3
"""Generate build/centaur/data.lua for tools/mgba/centaur.lua.

  python3 tools/mgba/gen_centaur_data.py [--trans ../boktai3trans]

Contents: per string ID, the Japanese (decoded from the extracted text bank)
and the English of the fan translation (boktai3trans scriptEd/script.sjs), as
plain display text (markup tags removed); plus resource type names and known
sprite notes for the overlay; and the scripts' debug `print` strings by their
raw EUC-JP bytes, with the English of gcl/prints.csv, for the print log. ROM- and translation-derived, so it stays in
build/ (ignored).
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(ROOT, "tools", "trans"))
from datafmt import load_manifest  # noqa: E402
import english  # noqa: E402
sys.path.insert(0, os.path.join(ROOT, "tools", "assets"))
import gclnames  # noqa: E402

TYPES = {0x922E: "anm", 0x92B3: "pal", 0x9B1B: "9B1B", 0x98F5: "bigspr", 0xA635: "fnt", 0xA8D9: "gcx",
         0xAE6C: "hp", 0xC091: "map", 0xCB05: "spr", 0xCEEF: "ptn", 0xCEAA: "CEAA"}


def display(s):
    s = re.sub(r"<[^>]*>", "", s)
    s = s.replace("\\n", "\n").replace("\\t", " ").replace("\\{", "{").replace("\\\\", "\\")
    s = re.sub(r"\\x[0-9a-fA-F]{2}", "", s)
    return s.strip("\n")


def lua_str(s):
    out = ['"']
    for ch in s:
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ord(ch) < 0x20:
            out.append(f"\\{ord(ch)}")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--trans", default=os.path.join(os.path.dirname(ROOT), "boktai3trans"))
    a = ap.parse_args()
    entry = next(e for e in load_manifest() if e.name == "text_bank")
    if not os.path.exists(entry.file):
        entry.extract()
    jp = {}
    for ln in open(entry.file, encoding="utf-8"):
        p = ln.rstrip("\n").split("\t")
        if len(p) > 2 and p[1] == "T":
            jp[int(p[0])] = display(p[2])
    en = {}
    script = os.path.join(a.trans, "scriptEd", "script.sjs")
    if os.path.exists(script):
        for sid, (j, e) in english.fan_script(script).items():
            if j and e and e != j:
                en[sid] = display(e)
    else:
        print(f"no translation at {script}; subtitles will show Japanese only")
    out_dir = os.path.join(ROOT, "build", "centaur")
    os.makedirs(out_dir, exist_ok=True)
    lines = ["-- generated by tools/mgba/gen_centaur_data.py; ROM-derived, do not commit", "return {", "jp = {"]
    lines += [f"[{i}]={lua_str(s)}," for i, s in sorted(jp.items()) if s]
    lines += ["},", "en = {"]
    lines += [f"[{i}]={lua_str(s)}," for i, s in sorted(en.items()) if s]
    lines += ["},", "types = {"]
    lines += [f"[0x{t:04X}]={lua_str(n)}," for t, n in TYPES.items()]
    lines += ["},", "prints = {"]
    for text, e in gclnames.prints().items():
        u = re.sub(r"\\(.)", lambda m: {"n": "\n"}.get(m.group(1), m.group(1)), text)  # gcx.py escapes
        raw = u.encode("euc_jp")
        lines.append("[\"" + "".join(f"\\{c}" for c in raw) + f"\"]={{jp={lua_str(u)}, en={lua_str(e)}}},")
    lines += ["},", "}"]
    path = os.path.join(out_dir, "data.lua")
    open(path, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"wrote {os.path.relpath(path, ROOT)}: {len(jp)} Japanese, {len(en)} English strings, "
          f"{len(gclnames.prints())} prints")


if __name__ == "__main__":
    main()
