#!/usr/bin/env python3
"""Scene entries in the script image, and the stage each one loads.

  python3 tools/mgba/scenes.py [--lua build/centaur/scenes.lua] [--json build/centaur/scenes.json]

Each scene also gets a default entrance (the first unconditional one found by
tools/assets/stages.py) for Centaur's warp(scene).

A scene is a script procedure that the `load` command (08225508) puts in
0x030039F0 and GameState+0x5A4 (the field scene of tests/saves/ShinBok2.sav is
3243). Scene entries begin `proc_861 1; proc_864 0|2`; the stage is the first
proc_884(map, tileset, hp) (or proc_885 or proc_876) reached from it (two calls deep). Note that
tools/assets/gcx.py prints procedure headers one lower than the IDs that calls
use: the body of scene 3243 is printed as "proc 3242".
"""
import argparse
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def scenes():
    out = subprocess.run([sys.executable, os.path.join(ROOT, "tools", "assets", "gcx.py"), "dis"],
                         cwd=ROOT, capture_output=True, text=True).stdout
    body, cur = {}, None
    for ln in out.split("\n"):
        m = re.match(r"proc (\d+) \(flag (\d+)\)", ln)
        if m:
            cur = int(m.group(1)) + 1  # call ID = printed header + 1
            body[cur] = []
            continue
        if cur:
            body[cur].append(ln.strip())

    def stage_of(pid, depth=0):
        for ln in body.get(pid, []):
            m = re.match(r"proc_(?:884|885|876) (0x\w+) (0x\w+) (0x\w+)", ln)
            if m:
                return [f"{int(x, 16):04X}" for x in m.groups()]
        if depth < 2:
            for ln in body.get(pid, []):
                m = re.match(r"proc_(\d+)", ln)
                if m:
                    s = stage_of(int(m.group(1)), depth + 1)
                    if s:
                        return s
        return None

    res = []
    for pid, b in sorted(body.items()):
        if len(b) >= 2 and b[0] == "proc_861 1 <end>" and b[1] in ("proc_864 0 <end>", "proc_864 2 <end>"):
            s = stage_of(pid)
            res.append({"scene": pid, "kind": int(b[1].split()[1]), "map": s[0] if s else None,
                        "tileset": s[1] if s else None, "hp": s[2] if s else None})
    return res


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lua", default=os.path.join(ROOT, "build", "centaur", "scenes.lua"))
    ap.add_argument("--json", default=os.path.join(ROOT, "build", "centaur", "scenes.json"))
    a = ap.parse_args()
    sc = scenes()
    for s in sc:
        s["entrance"] = None
    try:  # a default entrance per scene, for warp() (tools/assets/stages.py)
        sys.path.insert(0, os.path.join(ROOT, "tools", "assets"))
        import stages
        ents = {m["scene"]: m["entrances"] for m in stages.build({s["scene"] for s in sc})}
        for s in sc:
            es = ents.get(s["scene"], [])
            pick = ([e for e in es if not e["cond"] and e.get("x") is not None] or
                    [e for e in es if e.get("x") is not None] or es)
            s["entrance"] = pick[0]["id"] if pick else None
    except Exception as ex:  # the scene list is still useful without entrances
        print(f"no entrances: {ex}", file=sys.stderr)
    os.makedirs(os.path.dirname(a.lua), exist_ok=True)
    with open(a.lua, "w") as f:
        f.write("-- generated by tools/mgba/scenes.py\nreturn {\n")
        for s in sc:
            f.write('{scene=%d,kind=%d,map="%s",tileset="%s",entrance=%s},\n'
                    % (s["scene"], s["kind"], s["map"] or "", s["tileset"] or "",
                       s["entrance"] if s["entrance"] is not None else "nil"))
        f.write("}\n")
    json.dump(sc, open(a.json, "w"), indent=0)
    print(f"{len(sc)} scenes ({sum(1 for s in sc if s['map'])} with a stage) -> {os.path.relpath(a.lua, ROOT)}")


if __name__ == "__main__":
    main()
