#!/usr/bin/env python3
"""Write a debug scenario that fights the enemies of every scene.

  python3 tools/mgba/combat_scenario.py [OUT]     (default tests/scenarios/combat_all.txt)
  PALETTE_LOG=1 SCENARIO=tests/scenarios/combat_all.txt tools/mgba/headless.sh tools/mgba/scenario.lua

For each scene whose stage data places enemies (tools/assets/stages.py), the
scenario warps in, moves the player next to each of up to three enemies and
attacks in four directions (B, A, moving), so enemy attacks, hits, deaths and
projectiles run. With PALETTE_LOG the palettes they select are logged
(build/centaur/scenarios/combat_all/sprite_pools.tsv); tools/assets/
bigpalettes.py write folds every scenario log into data/sprite_palettes.csv.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "assets"))
sys.path.insert(0, os.path.join(HERE, ".."))
import stages  # noqa: E402
from romlib import ROOT  # noqa: E402


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "tests", "scenarios", "combat_all.txt")
    lines = ["# Generated by tools/mgba/combat_scenario.py: fight the enemies of every scene.", "from field"]
    n = 0
    for s in stages.build():
        es = [e for e in s["enemies"] if e.get("x") is not None]
        if not es or not s["stage"]:
            continue
        ent = next((e["id"] for e in s["entrances"] if e.get("id") is not None), None)
        n += 1
        lines += [f"warp {s['scene']}" + (f" {ent}" if ent is not None else ""), "wait 150"]
        for e in es[:3]:
            lines += [f"pos {e['x'] + 256} {e.get('y') or 0} {e['z']}", "wait 20"]
            for d in ("LEFT", "UP", "RIGHT", "DOWN"):
                lines += [f"keys {d}+B 25", "keys B 15", "keys A 10"]
            lines += ["wait 60"]
        lines += [f"shot scene_{s['scene']}"]
    open(out, "w").write("\n".join(lines) + "\n")
    print(f"{out}: {n} scenes")


if __name__ == "__main__":
    main()
