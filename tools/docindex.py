#!/usr/bin/env python3
"""The documentation index, and "who has written about this address?".

  docindex.py                 regenerate the file table in docs/INDEX.md
  docindex.py ADDR...         docs and notes that mention ADDR or cover it with a
                              range (08081290–08082648), plus its symbol and state
  docindex.py --tag TAG       files and history entries tagged #TAG

Tags are a `Tags: #a #b` line in a file's first lines (or under a history
entry's heading); the vocabulary is in docs/INDEX.md. Files without one get
tags guessed from their title and opening lines, shown in italics. Sizes are
there so an agent can judge what is worth reading in full.
"""
import csv
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INDEX = os.path.join(ROOT, "docs", "INDEX.md")
MARK = "<!-- generated by tools/docindex.py: everything below this line -->"
GLOBS = ["docs/*.md", "docs/tasks/*.md", "docs/history/*.md", "gcl/*.md", "gcl/examples/*.md", "notes/*.md"]
VOCAB = {
    "scripts": r"\bscripts?\b|GCL|gcx|script engine",
    "actors": r"\bactors?\b",
    "scene": r"\bscene\b",
    "inventory": r"inventor",
    "panel": r"\bpanel",
    "hud": r"\bHUD\b",
    "menu": r"\bmenus?\b",
    "wireless": r"wireless|RFU",
    "tether": r"tether",
    "particles": r"particle|emitter",
    "animation": r"animation",
    "sound": r"m4a|MP2K|\bsound\b|song",
    "hardware": r"\bRTC\b|EEPROM|solar sensor|SIIRTC",
    "library": r"libgcc|libm\b|fdlibm|SDK",
    "assets": r"sprite|palette|tileset|\bmaps?\b|asset|resource",
    "text": r"\btext\b|charmap|font|translation",
    "matching": r"agbcc|register alloc|permut|matching|nonmatching|draft",
    "tooling": r"\btools?/|tooling|studio|Centaur|harness|emulator",
    "progress": r"progress|decomp\.dev|report",
    "process": r"retrospective|benchmark|review|devlog|campaign|handoff|worker brief",
}
ADDR = re.compile(r"\b(?:0x)?(0?8[0-9A-Fa-f]{6})\b")
RANGE = re.compile(r"\b(?:0x)?(0?8[0-9A-Fa-f]{6})\s*(?:–|-|—|\.\.|to)\s*(?:0x)?(0?8[0-9A-Fa-f]{6})\b")


def files():
    out = []
    for g in GLOBS:
        out += sorted(glob.glob(os.path.join(ROOT, g)))
    return [f for f in out if os.path.abspath(f) != INDEX]


def info(path):
    text = open(path, encoding="utf-8", errors="replace").read()
    lines = text.split("\n")
    title = next((ln[2:].strip() for ln in lines if ln.startswith("# ")), os.path.basename(path))
    tags = []
    for ln in lines[:12]:
        m = re.match(r"\s*Tags:\s*(.*)", ln)
        if m:
            tags = re.findall(r"#([\w-]+)", m.group(1))
    if "docs/history/" in path:  # the union of the entries' tags
        tags = sorted({t for ln in lines if ln.startswith("Tags:") for t in re.findall(r"#([\w-]+)", ln)})
        guessed = False
    else:
        guessed = not tags
    if guessed:  # from the title and the first paragraph only
        body = "\n".join(lines[1:40]).strip("\n").split("\n\n")
        para = next((p for p in body if p.strip() and not p.startswith(("#", "Tags:", "|"))), "")
        tags = [t for t, rx in VOCAB.items() if re.search(rx, title, re.I)
                or (t not in ("process", "matching", "progress") and re.search(rx, para, re.I))]
    return {"path": os.path.relpath(path, ROOT), "title": title, "tags": tags, "guessed": guessed,
            "kb": len(text.encode()) / 1024, "text": text}


def regenerate():
    head = open(INDEX, encoding="utf-8").read().split(MARK)[0].rstrip("\n")
    rows = ["| File | Title | Tags | KB |", "|---|---|---|---:|"]
    for f in files():
        i = info(f)
        tags = " ".join("#" + t for t in i["tags"])
        tags = f"*{tags}*" if i["guessed"] and tags else tags
        title = i["title"].replace("|", "\\|")
        rows.append(f"| [{i['path']}](../{i['path']}) | {title} | {tags} | {i['kb']:.0f} |")
    open(INDEX, "w", encoding="utf-8").write(head + "\n\n" + MARK + "\n\n" + "\n".join(rows) + "\n")
    print(f"docs/INDEX.md: {len(rows) - 2} files")


def lookup(addr):
    a = int(addr, 16)
    name, state = None, "?"
    with open(os.path.join(ROOT, "symbols", "functions.csv")) as f:
        for r in csv.DictReader(f):
            if int(r["addr"], 16) == a:
                name = r["name"]
    src = glob.glob(os.path.join(ROOT, "src", "**", "*.c"), recursive=True)
    hit = [s for s in src if re.search(rf"\b(sub_)?{a:08X}\b|\b{re.escape(name or 'sub_%08X' % a)}\b",
                                       open(s, errors="replace").read())]
    state = "in C: " + ", ".join(os.path.relpath(s, ROOT) for s in hit[:3]) if hit else "no C file mentions it"
    print(f"{a:08X}  {name or f'sub_{a:08X} (unnamed)'}  ({state})")
    for f in files():
        i = info(f)
        found = []
        for n, ln in enumerate(i["text"].split("\n"), 1):
            if any(int(m, 16) == a for m in ADDR.findall(ln)):
                found.append((n, "mentions", ln.strip()))
            else:
                for lo, hi in RANGE.findall(ln):  # a subsystem's range, not a whole-ROM or worker split
                    if int(lo, 16) <= a <= int(hi, 16) and int(hi, 16) - int(lo, 16) <= 0x10000:
                        found.append((n, "range", ln.strip()))
                        break
        for n, kind, ln in found[:4]:
            print(f"  {i['path']}:{n}  [{kind}]  {ln[:140]}")
        if len(found) > 4:
            print(f"  {i['path']}: … {len(found) - 4} more")


def by_tag(tag):
    for f in files():
        i = info(f)
        if tag in i["tags"] and "docs/history/" not in i["path"]:
            print(f"{i['path']}  {i['title']}  ({i['kb']:.0f} KB)")
        if "docs/history/" in i["path"]:
            lines = i["text"].split("\n")
            for n, ln in enumerate(lines):
                if ln.startswith("Tags:") and f"#{tag}" in ln.split():
                    print(f"{i['path']}:{n}  {lines[n - 1][3:]}")


def main():
    args = sys.argv[1:]
    if not args:
        regenerate()
    elif args[0] == "--tag":
        by_tag(args[1].lstrip("#"))
    else:
        for a in args:
            lookup(a)


if __name__ == "__main__":
    main()
