#!/usr/bin/env python3
"""Native code the GCL scripts reach, and what of it is still unmatched.

  script_targets.py [--markdown FILE]

Script entry points are the registry routines (data/actor_registry.csv, run by
`chara` and `command`) and the native command handlers. From them this walks
the call graph of gen/code.s (`bl` targets and Thumb function pointers loaded
from literal pools, such as the callbacks a routine installs) and joins it
with tools/progress.py's per-function match state. It ranks the unmatched
entry points by how often the scripts use them, and the unmatched functions
by how many entry points call them directly: a decomp worklist for making the
script engine's surface readable C.
"""
import collections
import json
import os
import re
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
import actors  # noqa: E402
import gclnames  # noqa: E402
import gcloptions  # noqa: E402
import gcx  # noqa: E402
from romlib import load_rom  # noqa: E402


def progress():
    """{address: (size, matched, name, unit)} from tools/progress.py."""
    with tempfile.TemporaryDirectory() as d:
        f = os.path.join(d, "p.json")
        subprocess.run([sys.executable, os.path.join(ROOT, "tools", "progress.py"), "--json", f],
                       cwd=ROOT, check=True, capture_output=True)
        prog = json.load(open(f))
    out = {}
    for u in prog["units"]:
        for fn in u["functions"]:
            out[int(fn["metadata"]["virtual_address"])] = (int(fn["size"]), fn.get("fuzzy_match_percent", 0) == 100,
                                                          fn["name"], u["name"])
    return out


def edges(a):
    funcs, names = actors.code()
    out = set()
    for ln in funcs.get(a, {}).get("lines", []):
        m = re.match(r"\s*bl (\w+)", ln)
        if m and m.group(1) in names:
            out.add(names[m.group(1)])
        m = re.search(r"@ =0x(08[0-9A-F]{6})", ln)
        if m and int(m.group(1), 16) & 1 and int(m.group(1), 16) & ~1 in funcs:
            out.add(int(m.group(1), 16) & ~1)
    return out


def roots():
    """{address: ("registry", key) or ("command", name)}."""
    out = {}
    for k, r in actors.registry().items():
        out[int(r["callback"], 16) & ~1] = ("registry", k)
    cmds = {k: r["name"] for k, r in gclnames.best("command").items()}
    rom = load_rom()
    for table, n in gcloptions.CMD_TABLES:
        for i in range(n):
            k, f = struct.unpack_from("<II", rom, table - 0x08000000 + 8 * i)
            out[f & ~1] = ("command", cmds.get(k, f"cmd_{k:04X}"))
    return out


def uses():
    """Counter of script uses: ("registry", key) and ("command", name)."""
    img, c = actors.image(), collections.Counter()
    for cid in actors.procs():
        for _, t in gcx.disassemble(img, cid - 1):
            for m in re.finditer(r"\b(chara|command) (0x[0-9a-f]+)", t):
                c["registry", f"{int(m.group(2), 16):04X}"] += 1
            m = re.match(r"(\w+)", t)
            if m:
                c["command", m.group(1)] += 1
    return c


def report():
    fn, rt, use = progress(), roots(), uses()
    seen, q = set(rt), collections.deque(rt)
    while q:
        for b in edges(q.popleft()):
            if b not in seen:
                seen.add(b)
                q.append(b)
    total = sum(v[0] for v in fn.values())

    def stats(s):
        s = [a for a in s if a in fn]
        b = sum(fn[a][0] for a in s)
        m = sum(fn[a][0] for a in s if fn[a][1])
        return len(s), b, m

    names = gclnames.best("chara")
    lines = ["# Decomp targets: the code the scripts call", "",
             "Generated by `python3 tools/assets/script_targets.py --markdown docs/tasks/script_targets.md`.",
             "Script entry points are the registry routines (`chara`/`command` keys) and the native command",
             "handlers; their callees are found through `bl` calls and Thumb function pointers in gen/code.s.", "",
             "| Set | Functions | Bytes | Share of code | Matched |", "|---|---:|---:|---:|---:|"]
    direct = set(rt)
    for a in rt:
        direct |= edges(a)
    for label, s in (("Entry points", set(rt)), ("Entry points and their direct callees", direct),
                     ("Everything reachable from scripts", seen)):
        n, b, m = stats(s)
        lines.append(f"| {label} | {n} | {b:,} | {100 * b / total:.1f}% | {100 * m / b:.1f}% |")
    rows = []
    for a, (kind, k) in rt.items():
        if a in fn and not fn[a][1]:
            n = use[kind, k]
            label = (names.get(int(k, 16), {}).get("english", "") if kind == "registry" else k)
            rows.append((n, a, fn[a][0], fn[a][2], f"{kind} {k}", label))
    rows.sort(key=lambda r: (-r[0], r[1]))
    used = [r for r in rows if r[0]]
    lines += ["", f"## Unmatched entry points, by script uses ({len(used)} used, {sum(r[2] for r in used):,} bytes)", "",
              "| Uses | Address | Bytes | Function | Script name | GCL name |", "|---:|---|---:|---|---|---|"]
    lines += [f"| {r[0]} | `{r[1]:08X}` | {r[2]} | `{r[3]}` | {r[4]} | {r[5]} |" for r in used]
    callers = collections.Counter()
    for a in rt:
        for b in edges(a):
            callers[b] += 1
    shared = [(c, b) for b, c in callers.most_common() if b in fn and not fn[b][1] and c > 1 and b not in rt]
    lines += ["", "## Unmatched functions called directly by several entry points", "",
              "| Entry points | Address | Bytes | Function |", "|---:|---|---:|---|"]
    lines += [f"| {c} | `{b:08X}` | {fn[b][0]} | `{fn[b][2]}` |" for c, b in shared]
    return "\n".join(lines) + "\n"


def main():
    text = report()
    if "--markdown" in sys.argv:
        open(sys.argv[sys.argv.index("--markdown") + 1], "w").write(text)
    else:
        print(text)


if __name__ == "__main__":
    main()
