"""build_c inlines asm/macros.inc: gas misread an included file's first `@` comment at some buffer ends."""
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

import build  # noqa: E402

HEADER = ["@ Generated by gcc 2.9-arm-000512 for Thumb/elf", "\t.code\t16", ".gcc2_compiled.:",
          '\t.include "asm/macros.inc"', "\t.code\t16"]


def debug_strings(pad):
    """Compiler-like output over 32 KiB whose .debug_info strings start `pad` bytes later."""
    lines = HEADER + ["\t.section\t.debug_info", f'\t.ascii\t"{"x" * pad}\\000"']
    i = 0
    while sum(len(line) + 1 for line in lines) < 40000:
        lines += [f"\t.byte\t0x{i % 7 + 2:x}", f'\t.ascii\t"Member{i}Name\\000"', "\t.4byte\t0x0"]
        i += 1
    return "\n".join(lines) + "\n"


class InlineMacros(unittest.TestCase):
    def test_include_replaced_by_the_file(self):
        text = build.inline_macros("\n".join(HEADER) + "\n")
        self.assertNotIn('.include "asm/macros.inc"', text)
        self.assertIn((ROOT / "asm" / "macros.inc").read_text().strip(), text)
        self.assertTrue(text.endswith("\t.code\t16\n"))

    @unittest.skipUnless(shutil.which(build.AS[0]), "needs the ARM assembler")
    def test_every_buffer_end_assembles(self):
        # One string group is 51 bytes, so 0..55 moves gas's first buffer end through a whole
        # group; with the `.include` kept, pads 0 and 51 failed at asm/macros.inc:1 (binutils 2.47).
        with tempfile.TemporaryDirectory() as tmp:
            s, o = Path(tmp) / "u.s", Path(tmp) / "u.o"
            for pad in range(56):
                s.write_text(build.inline_macros(debug_strings(pad)))
                r = subprocess.run(build.AS + ["-o", str(o), str(s)], capture_output=True, text=True, cwd=ROOT)
                self.assertEqual(r.returncode, 0, f"pad {pad}: {r.stderr}")


if __name__ == "__main__":
    unittest.main()
